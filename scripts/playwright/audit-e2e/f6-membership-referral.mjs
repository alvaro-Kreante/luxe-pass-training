import { setPage, open, shot, login, step, dump, member, admin, BASE, env, PW } from "./lib.mjs";
import { createClient } from "@supabase/supabase-js";
const m = await member("memb");
const { browser, page, log } = await open(); setPage(page);
await login(page, m.email);
await step("F6.1 alta membresía mensual con 4242", async () => {
  await page.goto(BASE + "/profile/membership/plans", { waitUntil: "load" });
  await page.getByRole("button", { name: /Choose monthly/i }).click({ timeout: 20000 });
  const dlg = page.getByRole("dialog"); await dlg.waitFor(); await page.waitForTimeout(5000);
  const f = page.frameLocator('iframe[title="Secure payment input frame"]').first();
  await f.getByText("Card", { exact: true }).click().catch(() => {});
  await page.waitForTimeout(800);
  await f.getByRole("textbox", { name: /Card number/i }).fill("4242424242424242");
  await f.getByRole("textbox", { name: /Expiration date/i }).fill("12/34");
  await f.getByRole("textbox", { name: /Security code/i }).fill("123");
  const c = f.locator("#payment-countryInput"); if (await c.count()) await c.selectOption("US");
  const z = f.getByRole("textbox", { name: /ZIP|postal/i }); if (await z.count()) await z.fill("10017");
  await shot(page, "f6-upgrade-modal");
  const btns = await dlg.getByRole("button").allInnerTexts();
  await dlg.getByRole("button", { name: /pay|confirm|join|start/i }).last().click();
  await page.waitForTimeout(12000);
  await shot(page, "f6-upgrade-result");
  const ms = (await admin.from("memberships").select("plan,status").eq("member_id", m.id)).data;
  const pays = (await admin.from("payments").select("status,membership_plan,amount_cents").eq("member_id", m.id)).data;
  return `buttons=${JSON.stringify(btns)} memberships=${JSON.stringify(ms)} payments=${JSON.stringify(pays)}`;
});
await step("F6.2 cliente no puede escribir memberships (RLS)", async () => {
  const c = createClient(env.NEXT_PUBLIC_SUPABASE_URL, env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY, { auth: { persistSession: false } });
  const x = await member("memb-rls"); await c.auth.signInWithPassword({ email: x.email, password: PW });
  const ins = await c.from("memberships").insert({ member_id: x.id, plan: "annual", status: "active" });
  const upd = await c.from("memberships").update({ status: "active" }).eq("member_id", m.id).select();
  return `insert=${ins.error ? "DENIED " + ins.error.code : "ALLOWED"} updateOther=${upd.error ? "DENIED" : "rows=" + upd.data.length}`;
});
let code;
await step("F6.3 referidos: código + /join/[code] anónimo", async () => {
  await page.goto(BASE + "/profile/membership/referrals", { waitUntil: "load" }); await page.waitForTimeout(4000);
  await shot(page, "f6-referrals");
  const txt = await page.locator("body").innerText();
  code = (txt.match(/join\/([A-Za-z0-9-]+)/) || txt.match(/\b([A-Z0-9]{5,}-?[A-Z0-9]*)\b/))?.[1];
  const db = (await admin.from("referral_codes").select("*").eq("member_id", m.id)).data ?? null;
  if (db?.[0]?.code) code = db[0].code;
  const anon = await open({ width: 1440, height: 900 });
  const r = await anon.page.goto(BASE + "/join/" + code, { waitUntil: "load" }); await anon.page.waitForTimeout(3000);
  await shot(anon.page, "f6-join-valid");
  const t1 = (await anon.page.locator("body").innerText()).replace(/\s+/g, " ").slice(0, 200);
  await anon.page.goto(BASE + "/join/NOPE-INVALID", { waitUntil: "load" }); await anon.page.waitForTimeout(3000);
  await shot(anon.page, "f6-join-invalid");
  const t2 = (await anon.page.locator("body").innerText()).replace(/\s+/g, " ").slice(0, 200);
  await anon.browser.close();
  return `code=${code} status=${r.status()} valid="${t1}" invalid="${t2}"`;
});
dump("f6", log); await browser.close();
